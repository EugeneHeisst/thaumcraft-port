    private static void put(String old, int meta, Map<String, Integer> values) {
        if (meta == 32767 && (old.equals("wool") || old.equals("stained_hardened_clay") || old.equals("stained_glass") || old.equals("stained_glass_pane") || old.equals("carpet"))) {
            for (int i = 0; i < 16; i++) put(old, i, values);
            return;
        }
        if (meta == 32767 && (old.equals("log") || old.equals("leaves") || old.equals("planks") || old.equals("sapling"))) {
            for (int i = 0; i < (old.equals("log") || old.equals("leaves") ? 4 : 6); i++) put(old, i, values);
            return;
        }
        if (meta == 32767) meta = 0;
        String name = switch (old) {
            case "wool", "carpet" -> COLORS[Math.floorMod(meta,16)] + "_" + old;
            case "stained_hardened_clay" -> COLORS[Math.floorMod(meta,16)] + "_terracotta";
            case "stained_glass", "stained_glass_pane" -> COLORS[Math.floorMod(meta,16)] + "_" + old;
            case "log" -> WOODS[Math.floorMod(meta,4)] + "_log";
            case "log2" -> WOODS[4 + Math.floorMod(meta,2)] + "_log";
            case "leaves" -> WOODS[Math.floorMod(meta,4)] + "_leaves";
            case "leaves2" -> WOODS[4 + Math.floorMod(meta,2)] + "_leaves";
            case "planks", "sapling" -> WOODS[Math.floorMod(meta,6)] + "_" + old;
            case "grass" -> "grass_block";
            case "dirt" -> meta == 2 ? "podzol" : meta == 1 ? "coarse_dirt" : "dirt";
            case "sand" -> meta == 1 ? "red_sand" : "sand";
            case "reeds" -> "sugar_cane";
            case "waterlily" -> "lily_pad";
            case "deadbush" -> "dead_bush";
            case "hardened_clay" -> "terracotta";
            case "snow_layer" -> "snow";
            case "snow" -> "snow_block";
            case "lit_pumpkin" -> "jack_o_lantern";
            case "melon_block" -> "melon";
            case "melon" -> "melon_slice";
            case "speckled_melon" -> "glistering_melon_slice";
            case "netherbrick" -> "nether_brick";
            case "nether_brick" -> "nether_bricks";
            case "nether_wart" -> "nether_wart";
            case "golden_rail" -> "powered_rail";
            case "brick_block" -> "bricks";
            case "quartz_block" -> meta == 1 ? "chiseled_quartz_block" : meta == 2 ? "quartz_pillar" : "quartz_block";
            case "stonebrick" -> new String[]{"stone_bricks","mossy_stone_bricks","cracked_stone_bricks","chiseled_stone_bricks"}[Math.floorMod(meta,4)];
            case "yellow_flower" -> "dandelion";
            case "red_flower" -> new String[]{"poppy","blue_orchid","allium","azure_bluet","red_tulip","orange_tulip","white_tulip","pink_tulip","oxeye_daisy"}[Math.floorMod(meta,9)];
            case "fish" -> new String[]{"cod","salmon","tropical_fish","pufferfish"}[Math.floorMod(meta,4)];
            case "cooked_fished" -> meta == 1 ? "cooked_salmon" : "cooked_cod";
            case "skull" -> new String[]{"skeleton_skull","wither_skeleton_skull","zombie_head","player_head","creeper_head"}[Math.floorMod(meta,5)];
            case "dye" -> new String[]{"ink_sac","red_dye","green_dye","cocoa_beans","lapis_lazuli","purple_dye","cyan_dye","light_gray_dye","gray_dye","pink_dye","lime_dye","yellow_dye","light_blue_dye","magenta_dye","orange_dye","bone_meal"}[Math.floorMod(meta,16)];
            case "coal" -> meta == 1 ? "charcoal" : "coal";
            case "water", "flowing_water" -> "water";
            case "lava", "flowing_lava" -> "lava";
            default -> old;
        };
        ResourceLocation id = ResourceLocation.fromNamespaceAndPath("minecraft", name);
        TAGS.put(id.toString(), values);
    }
